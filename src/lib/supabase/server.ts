import "server-only";
import { createServerClient } from "@supabase/ssr";
import { cookies } from "next/headers";
import { supabaseEnv } from "./env";

/**
 * Client Supabase legato alla sessione dell'utente: ogni query è soggetta
 * alle policy RLS, quindi vede soltanto i workspace di cui l'utente è membro.
 */
export async function createClient() {
  const cookieStore = await cookies();
  const { url, key } = supabaseEnv();

  return createServerClient(url, key, {
    cookies: {
      getAll: () => cookieStore.getAll(),
      setAll: (cookiesToSet) => {
        try {
          for (const { name, value, options } of cookiesToSet) {
            cookieStore.set(name, value, options);
          }
        } catch {
          // Chiamata da un Server Component: i cookie li aggiorna il proxy.
        }
      },
    },
  });
}
